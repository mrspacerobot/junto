import { writeFileSync, readFileSync, mkdirSync } from 'fs'
import { fileURLToPath, URL } from 'url'
import { dirname, join } from 'path'

const __dirname = dirname(fileURLToPath(import.meta.url))

// Read the config mapping: backend iconName → lucide SVG filename
const mapping: Record<string, string> = JSON.parse(
  readFileSync(join(__dirname, '../src/config/icon-names.json'), 'utf-8')
)

// Read each SVG from lucide-static, strip outer <svg> tag, keep inner elements
const entries = Object.entries(mapping).map(([iconName, lucideName]) => {
  const svgPath = join(__dirname, `../node_modules/lucide-static/icons/${lucideName}.svg`)
  try {
    const raw = readFileSync(svgPath, 'utf-8')
    const inner = raw
      .replace(/<svg[^>]*>/, '')
      .replace(/<\/svg>/, '')
      .trim()
    return { iconName, inner }
  } catch {
    console.warn(`⚠ Lucide icon "${lucideName}" not found (mapped from "${iconName}"), skipping`)
    return null
  }
}).filter(Boolean)

// Generate TypeScript file
const output = `// AUTO-GENERATED by scripts/generate-icon-map.ts — do not edit manually
// Regenerate: npm run generate-icons

export const iconMap: Record<string, string> = {
${entries.map(e => `  '${e!.iconName}': '${e!.inner.replace(/'/g, "\\'")}',`).join('\n')}
}

export const DEFAULT_ICON = '<circle cx="12" cy="12" r="10"/>'
`

mkdirSync(join(__dirname, '../src/generated'), { recursive: true })
writeFileSync(join(__dirname, '../src/generated/icon-map.ts'), output)
console.log(`✓ Generated icon map with ${entries.length} icons`)